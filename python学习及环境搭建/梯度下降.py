import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# 1. 数据准备
# ============================================================
X = np.array([100, 160, 240, 98, 76, 200, 50, 180, 160], dtype=float)
y = np.array([230, 330, 450, 232, 160, 489, 98, 400, 345], dtype=float)

m = len(X)  # 样本数 = 9

# ============================================================
# 2. 梯度下降初始化
# ============================================================
w = 0.0  # 斜率
b = 0.0  # 截距
lr = 5e-7  # 学习率（数据量级大，必须很小）
epochs = 200  # 迭代次数（比之前多，收敛更好）

# ============================================================
# 3. 梯度下降训练
# ============================================================
for i in range(epochs):
    # 前向计算：预测值
    y_pred = w * X + b

    # 计算梯度
    dw = (2 / m) * np.sum((y_pred - y) * X)
    db = (2 / m) * np.sum(y_pred - y)

    # 更新参数（沿梯度反方向走一步）
    w -= lr * dw
    b -= lr * db

# 打印训练结果
print(f"训练完成：w = {w:.4f}, b = {b:.4f}")

# ============================================================
# 4. 画图（完全匹配幻灯片右下角小图）
# ============================================================
plt.figure(figsize=(6, 4.5))

# 4.1 散点，图例只写 training set
plt.scatter(X, y, color='steelblue', label='training set')

# 4.2 画拟合直线（不写 label，所以图例里不会出现 prediction）
x_line = np.linspace(X.min(), X.max(), 100)
y_line = w * x_line + b
plt.plot(x_line, y_line, color='darkblue', linewidth=1.5)

# 4.3 坐标轴标签
plt.xlabel('Area')
plt.ylabel('Price')

# 4.4 图例（只有 training set）
plt.legend()

# 4.5 显示
plt.show()
